#ifndef SW_TYPES_H
#define SW_TYPES_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* -------------------------------------------------------------------------
 * 布尔类型别名
 * ------------------------------------------------------------------------- */
#ifndef TRUE
#define TRUE (1U)
#endif

#ifndef FALSE
#define FALSE (0U)
#endif

/* -------------------------------------------------------------------------
 * 空指针
 * ------------------------------------------------------------------------- */
#ifndef NULL
#define NULL ((void *)0)
#endif

/* -------------------------------------------------------------------------
 * 位操作宏
 * ------------------------------------------------------------------------- */
#define BIT(n)        (1UL << (n))
#define SET_BIT(x, n) ((x) |= BIT(n))
#define CLR_BIT(x, n) ((x) &= ~BIT(n))
#define GET_BIT(x, n) (((x) >> (n)) & 1UL)

/* -------------------------------------------------------------------------
 * 通用工具宏
 * ------------------------------------------------------------------------- */
#define ARRAY_SIZE(arr)    (sizeof(arr) / sizeof((arr)[0]))
#define MIN(a, b)          (((a) < (b)) ? (a) : (b))
#define MAX(a, b)          (((a) > (b)) ? (a) : (b))
#define CLAMP(val, lo, hi) (MIN(MAX((val), (lo)), (hi)))

/* -------------------------------------------------------------------------
 * 强制内联 / 未使用参数抑制
 * ------------------------------------------------------------------------- */
#define UNUSED(x) ((void)(x))

#endif /* SW_TYPES_H */
