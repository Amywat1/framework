#ifndef DOMAIN_ALARM_CODE_H
#define DOMAIN_ALARM_CODE_H

/* -------------------------------------------------------------------------
 * 安全类报警（8100~8199）
 * ------------------------------------------------------------------------- */
#define ALARM_CODE_ESTOP            8100U /* 急停按钮触发（常闭断开）*/

/* -------------------------------------------------------------------------
 * 限位异常报警（8001~8099）
 * ------------------------------------------------------------------------- */
#define ALARM_CODE_GANTRY_FWD_LIM   8001U /* 龙门前限位异常（同时触发前后限位）*/
#define ALARM_CODE_GANTRY_REV_LIM   8002U /* 龙门后限位异常 */
#define ALARM_CODE_LIFT_UP_LIM      8003U /* 顶刷升降上限位异常 */
#define ALARM_CODE_LIFT_DOWN_LIM    8004U /* 顶刷升降下限位异常 */

/* -------------------------------------------------------------------------
 * 驱动故障报警（8010~8019）
 * ------------------------------------------------------------------------- */
#define ALARM_CODE_VFD_GANTRY       8010U /* 龙门 VFD 故障 */
#define ALARM_CODE_VFD_BRUSH        8011U /* 刷子 VFD 故障 */
#define ALARM_CODE_STEPPER_FAULT    8012U /* 顶刷升降步进驱动器故障 */

/* -------------------------------------------------------------------------
 * 通信故障报警（8020~8029）
 * ------------------------------------------------------------------------- */
#define ALARM_CODE_MODBUS_GANTRY    8020U /* 龙门 Modbus 通信超时 */
#define ALARM_CODE_MODBUS_BRUSH     8021U /* 刷子 Modbus 通信超时 */

/* -------------------------------------------------------------------------
 * 云端/网络报警（8030~8039）
 * ------------------------------------------------------------------------- */
#define ALARM_CODE_MQTT_OFFLINE     8030U /* 云端 MQTT 断线（NOTICE 级，不停机）*/

#endif /* DOMAIN_ALARM_CODE_H */
